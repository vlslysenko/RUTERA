-- RUTERA schema, step 11: CMR consignment notes (group 5 of docs/DB_SCHEMA.md).
-- Conventions as in V1 (docs/DB_SCHEMA.md section 0); rows are deleted physically (only drafts).
-- Deviations from the sketch: the table holds CMR notes issued by RUTERA (source GENERATED); scans with OCR can use
-- the same table later (source UPLOADED, ocr_* columns then). Parties, goods lines, successive carriers and
-- signatures are JSON (always replaced as a whole). The box numbers follow the CMR form (1-24).

-- status: DRAFT, ISSUED, CANCELLED. Party JSON: {name, address, country, vatId}. goods JSON: [{marks, packages,
-- packing, nature, statNumber, grossWeightKg, volumeM3}]. signatures JSON: {sender, carrier, consignee: {name,
-- place, date}}. payment_terms: PAID, FORWARD. (goods: "lines" is a reserved word in MySQL.)
CREATE TABLE cmr_document (
    id                       BIGINT        NOT NULL AUTO_INCREMENT,
    firma_id                 BIGINT        NOT NULL,
    number                   VARCHAR(32)   NOT NULL,
    status                   VARCHAR(16)   NOT NULL,
    source                   VARCHAR(16)   NOT NULL DEFAULT 'GENERATED',
    order_id                 BIGINT        NULL,
    trip_id                  BIGINT        NULL,
    sender                   JSON          NULL,
    sender_contractor_id     BIGINT        NULL,
    consignee                JSON          NULL,
    consignee_contractor_id  BIGINT        NULL,
    carrier                  JSON          NULL,
    successive_carriers      JSON          NULL,
    delivery_place           VARCHAR(200)  NULL,
    delivery_country         CHAR(2)       NULL,
    loading_place            VARCHAR(200)  NULL,
    loading_country          CHAR(2)       NULL,
    loading_date             DATE          NULL,
    documents_attached       VARCHAR(500)  NULL,
    goods                    JSON          NULL,
    sender_instructions      VARCHAR(1000) NULL,
    payment_terms            VARCHAR(16)   NULL,
    payment_instructions     VARCHAR(500)  NULL,
    cod_amount               DECIMAL(14,2) NULL,
    cod_currency             CHAR(3)       NULL,
    carrier_reservations     VARCHAR(1000) NULL,
    special_agreements       VARCHAR(1000) NULL,
    established_place        VARCHAR(100)  NULL,
    established_date         DATE          NULL,
    vehicle_plates           VARCHAR(64)   NULL,
    signatures               JSON          NULL,
    notes                    VARCHAR(2000) NULL,
    file_id                  BIGINT        NULL,
    issued_at                DATETIME(6)   NULL,
    issued_by                BIGINT        NULL,
    created_at               DATETIME(6)   NOT NULL,
    created_by               BIGINT        NULL,
    updated_at               DATETIME(6)   NULL,
    updated_by               BIGINT        NULL,
    version                  INT           NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY ux_cmr_document_firma_number (firma_id, number),
    KEY ix_cmr_document_firma_order (firma_id, order_id),
    KEY ix_cmr_document_firma_trip (firma_id, trip_id),
    KEY ix_cmr_document_firma_loading (firma_id, loading_date),
    CONSTRAINT fk_cmr_document_firma_id FOREIGN KEY (firma_id) REFERENCES firma (id),
    CONSTRAINT fk_cmr_document_order_id FOREIGN KEY (order_id) REFERENCES transport_order (id),
    CONSTRAINT fk_cmr_document_trip_id FOREIGN KEY (trip_id) REFERENCES trip (id),
    CONSTRAINT fk_cmr_document_sender_contractor_id FOREIGN KEY (sender_contractor_id) REFERENCES contractor (id),
    CONSTRAINT fk_cmr_document_consignee_contractor_id FOREIGN KEY (consignee_contractor_id) REFERENCES contractor (id),
    CONSTRAINT fk_cmr_document_file_id FOREIGN KEY (file_id) REFERENCES stored_file (id),
    CONSTRAINT fk_cmr_document_issued_by FOREIGN KEY (issued_by) REFERENCES app_user (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;
